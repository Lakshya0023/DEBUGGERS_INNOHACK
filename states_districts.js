// Helper functions for State-District cascades across all frontend forms and filters
function getStatesList() {
    return Object.keys(STATES_DISTRICTS_DATA).sort();
}

function getDistrictsForState(stateName) {
    if (!stateName || !STATES_DISTRICTS_DATA[stateName]) return [];
    return [...STATES_DISTRICTS_DATA[stateName]].sort();
}

function getStateForDistrict(districtName) {
    if (!districtName) return '';
    const dLower = districtName.toLowerCase().trim();
    for (const [state, districts] of Object.entries(STATES_DISTRICTS_DATA)) {
        if (districts.some(d => d.toLowerCase().trim() === dLower || dLower.includes(d.toLowerCase().trim()) || d.toLowerCase().trim().includes(dLower))) {
            return state;
        }
    }
    return '';
}

function populateStateDropdown(stateSelectEl, placeholder = 'Select State') {
    if (!stateSelectEl) return;
    const currentVal = stateSelectEl.value;
    stateSelectEl.innerHTML = `<option value="">${placeholder}</option>`;
    getStatesList().forEach(state => {
        const opt = document.createElement('option');
        opt.value = state;
        opt.textContent = state;
        stateSelectEl.appendChild(opt);
    });
    if (currentVal) stateSelectEl.value = currentVal;
}

function populateDistrictDropdown(districtSelectEl, stateName, placeholder = 'Select District') {
    if (!districtSelectEl) return;
    const currentVal = districtSelectEl.value;
    districtSelectEl.innerHTML = `<option value="">${placeholder}</option>`;
    if (!stateName) {
        districtSelectEl.disabled = true;
        return;
    }
    districtSelectEl.disabled = false;
    const districts = getDistrictsForState(stateName);
    districts.forEach(dist => {
        const opt = document.createElement('option');
        opt.value = dist;
        opt.textContent = dist;
        districtSelectEl.appendChild(opt);
    });
    if (currentVal && districts.includes(currentVal)) {
        districtSelectEl.value = currentVal;
    }
}

function setupStateDistrictCascade(stateSelectEl, districtSelectEl, onDistrictChange = null, allDistrictsOption = false) {
    if (!stateSelectEl || !districtSelectEl) return;
    
    populateStateDropdown(stateSelectEl, allDistrictsOption ? 'All States (Pan India)' : 'Select State');
    
    if (allDistrictsOption) {
        districtSelectEl.innerHTML = '<option value="">All Districts</option>';
        districtSelectEl.disabled = false;
    } else {
        districtSelectEl.innerHTML = '<option value="">Select District</option>';
        districtSelectEl.disabled = true;
    }
    
    stateSelectEl.addEventListener('change', () => {
        const selectedState = stateSelectEl.value;
        if (!selectedState) {
            if (allDistrictsOption) {
                districtSelectEl.innerHTML = '<option value="">All Districts</option>';
                districtSelectEl.disabled = false;
            } else {
                districtSelectEl.innerHTML = '<option value="">Select District</option>';
                districtSelectEl.disabled = true;
            }
        } else {
            populateDistrictDropdown(
                districtSelectEl, 
                selectedState, 
                allDistrictsOption ? `All Districts in ${selectedState}` : 'Select District'
            );
        }
        if (onDistrictChange) onDistrictChange();
    });

    if (districtSelectEl && onDistrictChange) {
        districtSelectEl.addEventListener('change', onDistrictChange);
    }
}
